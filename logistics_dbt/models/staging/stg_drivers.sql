SELECT 
      CAST(DRIVER_ID AS VARCHAR(255)) AS DRIVER_ID,
      CAST(FIRST_NAME AS VARCHAR(255)) AS FIRST_NAME,
      CAST(LAST_NAME AS VARCHAR(255)) AS LAST_NAME,
      CAST(CONCAT(FIRST_NAME, ' ', LAST_NAME) AS VARCHAR(255))AS FULL_NAME,
      HIRE_DATE,
      TERMINATION_DATE,
      CAST(LICENSE_NUMBER AS VARCHAR(255)) AS LICENSE_NUMBER,
      CAST(LICENSE_STATE AS VARCHAR(255)) AS LICENSE_STATE,
      DATE_OF_BIRTH,
      CAST(HOME_TERMINAL AS VARCHAR(255)) AS HOME_TERMINAL,
      CAST(EMPLOYMENT_STATUS AS VARCHAR(255)) AS EMPLOYMENT_STATUS,
      CAST(CDL_CLASS AS VARCHAR(255)) AS CDL_CLASS,
      CAST(YEARS_EXPERIENCE AS INTEGER) AS YEARS_EXPERIENCE,
      CASE 
        WHEN DATE_OF_BIRTH IS NOT NULL THEN datediff('YEAR', DATE_OF_BIRTH, CURRENT_DATE)
        ELSE NULL
      END AS AGE,

FROM {{ source('logistics', 'drivers') }}